"""Master data for the Kaveri 3.0 legal document templates and field workbook.

Structure is modelled on the registered Sale Deed endorsement
(Sale Deed Filled-Template/Endorsement_740241_*.pdf):
    Part I   - Document Header (e-Stamp, parties summary, stamp duty, article, challan)
    Part II  - Schedules (property imported from e-Swathu / e-Aasthi / Bhoomi)
    Part III - Title Flow / Consideration Payments / Terms & Conditions
    Part IV  - Executants and Witnesses (Aadhaar e-KYC, e-Sign)
    Part V   - Endorsement by Sub-Registrar

Stamp articles refer to the Karnataka Stamp Act, 1957 and use the same
Nature-of-Document codes (DN-xx) as Acts_Rules/Document/_stamp_article_inputs_data.py.
Article and registration columns are indicative; the Stamp Duty Article module
makes the final determination.
"""

