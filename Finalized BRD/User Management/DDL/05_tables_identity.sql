-- OFFICIAL_EMAIL_DOMAIN (FR-UM-064)
CREATE TABLE IF NOT EXISTS um.official_email_domain (
  domain     varchar(120) PRIMARY KEY,
  is_active  boolean NOT NULL DEFAULT true
);

COMMENT ON TABLE um.official_email_domain IS
  'Permitted official email domain allow-list for DSR / Other Department creation (FR-UM-064); empty = no domain restriction enforced';

-- SECURITY_QUESTION (FR-UM-055)
CREATE TABLE IF NOT EXISTS um.security_question (
  question_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_text  varchar(500) NOT NULL,
  is_active      boolean NOT NULL DEFAULT true,
  display_order  integer NOT NULL DEFAULT 0
);

COMMENT ON TABLE um.security_question IS
  'Predefined list a Citizen picks 5 of at registration (FR-UM-055); 3 asked at random on lost-mobile reset (FR-UM-056)';

